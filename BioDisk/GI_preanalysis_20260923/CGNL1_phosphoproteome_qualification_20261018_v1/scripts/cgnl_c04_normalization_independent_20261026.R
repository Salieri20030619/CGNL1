library(jsonlite)
w <- '/mnt/BioDisk/wangmingyuan/GI_preanalysis_20260923/CGNL1_phosphoproteome_qualification_20261018_v1/continuous_exploration_20261023_v1/C04_full_fraction_qualification/reporter_normalization_20261026'
read <- function(n) read.delim(file.path(w,n),check.names=FALSE,stringsAsFactors=FALSE,na.strings='')
channels<-c('127n','127c','128n','128c','129n','129c','130n','130c')
ms<-read('REFERENCE_MS3.tsv');features<-read('REFERENCE_FEATURES.tsv');factors<-read('NORMALIZATION_FACTORS.tsv');raw<-read('CGNL1_RAW_REPORTERS.tsv');norm<-read('CGNL1_NORMALIZED_REPORTERS.tsv')
stopifnot(nrow(ms)==5068,nrow(features)==2823,!anyDuplicated(paste(ms$file,ms$MS3)))
key<-paste(ms$peptide,ms$phosphate_count,sep='|');expected_key<-paste(features$peptide,features$phosphate_count,sep='|')
sums<-rowsum(as.matrix(ms[,channels]),group=key,reorder=FALSE)
stopifnot(setequal(rownames(sums),expected_key),all(sums>0))
expected<-as.matrix(features[,channels]);actual<-sums[expected_key,,drop=FALSE]
aggregation_error<-max(abs(actual-expected)/pmax(1,abs(expected)))
centered<-sweep(log2(sums),1,rowMeans(log2(sums)),'-')
n1<-apply(centered,2,median);n1<-n1-mean(n1)
n2<-log2(colSums(sums));n2<-n2-mean(n2)
offsets<-list(N0=setNames(rep(0,8),channels),N1=n1,N2=n2)
factor_error<-max(vapply(seq_len(nrow(factors)),function(i)abs(offsets[[factors$model[i]]][factors$channel[i]]-factors$log2_offset[i]),0))
divisor_error<-max(abs(2^factors$log2_offset-factors$divisor))
rawkey<-paste(raw$file,raw$MS3,raw$channel);normkey<-paste(norm$file,norm$MS3,norm$channel)
stopifnot(!anyDuplicated(rawkey),!anyDuplicated(paste(normkey,norm$model)))
idx<-match(normkey,rawkey);stopifnot(!anyNA(idx))
stopifnot(identical(is.na(norm$normalized_log2),is.na(raw$intensity[idx])))
calc<-vapply(seq_len(nrow(norm)),function(i)if(is.na(raw$intensity[idx[i]]))NA_real_ else log2(raw$intensity[idx[i]])-offsets[[norm$model[i]]][norm$channel[i]],0)
normalization_error<-max(abs(calc-norm$normalized_log2),na.rm=TRUE)
stopifnot(aggregation_error<1e-12,factor_error<1e-10,divisor_error<1e-10,normalization_error<1e-10,nrow(norm)==96,sum(is.na(calc))==9)
result<-list(pass=TRUE,reference_MS3=nrow(ms),reference_features=nrow(features),aggregation_max_relative_error=aggregation_error,factor_max_absolute_error=factor_error,divisor_max_absolute_error=divisor_error,normalized_log2_max_absolute_error=normalization_error,normalized_values=87,missing_values_preserved=9,new_biological_tests=0)
write_json(result,file.path(w,'INDEPENDENT_R_NORMALIZATION_QA.json'),auto_unbox=TRUE,pretty=TRUE,digits=17)
cat(toJSON(result,auto_unbox=TRUE,digits=17),'\n')
